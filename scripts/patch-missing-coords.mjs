let fixed = 0;
const stillMissing = [];

for (const c of cities) {
  if (c.lat !== null && c.lon !== null) continue;

  const m = MANUAL[c.name];
  if (m) {
    c.lat = m[0];
    c.lon = m[1];
    c.coordSource = "manual";
    fixed++;
  } else if (c.level === 2 && c.city) {
    /* 区县：继承父城市 */
    const parent = cities.find(
      (x) => x.level === 1 && x.name === c.city && x.lat !== null
    );
    if (parent) {
      c.lat = parent.lat;
      c.lon = parent.lon;
      c.coordSource = "fallback-city";
      fixed++;
    } else {
      stillMissing.push(c.name);
    }
  } else {
    stillMissing.push(c.name);
  }
}

writeFileSync(CITIES_PATH, JSON.stringify(cities), "utf8");

const withCoords = cities.filter((c) => c.lat !== null && c.lon !== null).length;

console.log(`补充修正: ${fixed} 条`);
console.log(`有坐标: ${withCoords} / ${cities.length}`);
console.log(`仍缺失: ${cities.length - withCoords}`);
if (stillMissing.length) {
  console.log(`仍缺失的地名（前 20）: ${stillMissing.slice(0, 20).join("、")}`);
}
