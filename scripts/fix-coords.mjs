/**
 * 坐标修正脚本
 *
 * 用法: node scripts/fix-coords.mjs
 *
 * 背景：初次补坐标时，geocoding API 是全球搜索，重名地名会匹配到国外。
 *   例如「黑山」（辽宁锦州的一个区）匹配到了黑山共和国（欧洲）。
 *   又例如「张家口」匹配到了四川南充，导致该市所有区县坐标全错。
 *
 * 修正策略：
 *   1. 找出所有坐标不在中国范围内的记录 -> 清空重查
 *   2. 找出坐标与其所属省份/城市差距过大的记录 -> 清空重查
 *   3. 重查时：过滤掉不在中国范围的结果，且要求结果名或省份匹配
 *   4. 仍然查不到的：地级市用手工坐标表兜底；区县继承父城市坐标
 */

