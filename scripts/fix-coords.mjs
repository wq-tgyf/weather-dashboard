console.log("检查中...\n");

const problems = [];

/* 建立地级市索引（用于校验区县） */
const cityIndex = new Map();
for (const c of cities) {
  if (c.level === 1) cityIndex.set(c.name, c);
}

for (const c of cities) {
  if (c.lat === null || c.lon === null) continue;

  /* (a) 不在中国范围内 */
  if (!inChina(c.lat, c.lon)) {
    problems.push({ city: c, reason: "坐标在国外" });
    continue;
  }

  /* (b) 地级市：与手工坐标表差距过大 */
  if (c.level === 1 && CITY_COORDS[c.name]) {
    const [tLat, tLon] = CITY_COORDS[c.name];
    if (Math.abs(c.lat - tLat) > 1.0 || Math.abs(c.lon - tLon) > 1.0) {
      problems.push({
        city: c,
        reason: `地级市坐标偏离权威值（当前 ${c.lat},${c.lon}，应为 ${tLat},${tLon}）`,
      });
      continue;
    }
  }

  /* (c) 区县：与所属地级市的坐标差距过大 */
  if (c.level === 2 && c.city) {
    const parent = cityIndex.get(c.city);
    if (parent && parent.lat !== null) {
      const d = Math.sqrt(
        (c.lat - parent.lat) ** 2 + (c.lon - parent.lon) ** 2
      );
      if (d > 1.5) {
        problems.push({
          city: c,
          reason: `区县距所属城市 ${c.city} 过远（${d.toFixed(1)}°）`,
        });
      }
    }
  }
}

console.log(`发现 ${problems.length} 条问题记录\n`);

/* ------------------------------------------------------------------ */
/* 2. 先修正地级市（用权威坐标表直接覆盖）                               */
/* ------------------------------------------------------------------ */

let cityFixed = 0;
for (const c of cities) {
  if (c.level !== 1) continue;
  const known = CITY_COORDS[c.name];
  if (!known) continue;

  const [lat, lon] = known;
  const needsFix =
    c.lat === null ||
    !inChina(c.lat, c.lon) ||
    Math.abs(c.lat - lat) > 1.0 ||
    Math.abs(c.lon - lon) > 1.0;

  if (needsFix) {
    c.lat = lat;
    c.lon = lon;
    c.coordSource = "manual";
    cityFixed++;
  }
}

console.log(`地级市坐标修正: ${cityFixed} 个（使用权威坐标表）`);

/* ------------------------------------------------------------------ */
/* 3. 修正区县                                                         */
/* ------------------------------------------------------------------ */

const cityByName = new Map();
for (const c of cities) {
  if (c.level === 1 && c.lat !== null) cityByName.set(c.name, c);
}

let districtFixed = 0;
let districtFallback = 0;

for (const c of cities) {
  if (c.level !== 2) continue;

  const parent = c.city ? cityByName.get(c.city) : null;

  const isBad =
    c.lat === null ||
    !inChina(c.lat, c.lon) ||
    (parent &&
      parent.lat !== null &&
      Math.sqrt((c.lat - parent.lat) ** 2 + (c.lon - parent.lon) ** 2) > 1.5);

  if (!isBad) continue;

  /* 优先：用「区县名」重新查询（此时父城市坐标已修正） */
  let fixed = false;
  try {
    const url = new URL("https://geocoding-api.open-meteo.com/v1/search");
    url.searchParams.set("name", c.name);
    url.searchParams.set("count", "10");
    url.searchParams.set("language", "zh");
    url.searchParams.set("format", "json");

    const res = await fetch(url, { signal: AbortSignal.timeout(12000) });
    if (res.ok) {
      const json = await res.json();
      const results = (json.results ?? []).filter((r) => inChina(r.latitude, r.longitude));

      /* 要求结果与父城市距离合理（< 2 度） */
      const good = results.find((r) => {
        if (!parent || parent.lat === null) return true;
        const d = Math.sqrt(
          (r.latitude - parent.lat) ** 2 + (r.longitude - parent.lon) ** 2
        );
        return d < 2;
      });

      if (good) {
        c.lat = Number(good.latitude.toFixed(4));
        c.lon = Number(good.longitude.toFixed(4));
        c.coordSource = "geocoding-fixed";
        fixed = true;
        districtFixed++;
      }
    }
    await sleep(150);
  } catch {
    /* 忽略，走兜底 */
  }

  /* 兜底：继承父城市坐标 */
  if (!fixed && parent && parent.lat !== null) {
    c.lat = parent.lat;
    c.lon = parent.lon;
    c.coordSource = "fallback-city";
    districtFallback++;
  }
}

console.log(`区县坐标修正: ${districtFixed} 个（重新查询成功）`);
console.log(`区县兜底:   ${districtFallback} 个（继承所属城市坐标）`);

/* ------------------------------------------------------------------ */
/* 4. 写出并复查                                                       */
/* ------------------------------------------------------------------ */

writeFileSync(CITIES_PATH, JSON.stringify(cities), "utf8");

